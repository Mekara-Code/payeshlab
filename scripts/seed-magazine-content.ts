async function main() {
  const connectionString = process.env.DIRECT_URL ?? process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error("DIRECT_URL or DATABASE_URL must be configured.");
  }

  const prisma = new PrismaClient({
    adapter: new PrismaPg({ connectionString }),
  });

  try {
    const admin = await prisma.adminUser.findFirst({
      orderBy: { createdAt: "asc" },
      select: { id: true },
      where: { isActive: true },
    });

    if (!admin) {
      throw new Error("No active administrator was found to own the magazine content.");
    }

    for (const entry of entries) {
      const categories = await Promise.all(
        entry.categories.map(async (name) => {
          const slug = categorySlugs[name];
          if (!slug) throw new Error(`Missing category slug for ${name}.`);

          return prisma.articleCategory.upsert({
            create: { name, slug },
            select: { id: true },
            update: {},
            where: { name },
          });
        }),
      );

      const data = {
        content: entry.content as Prisma.InputJsonValue,
        excerpt: entry.excerpt,
        featuredImage: entry.featuredImage,
        metaDescription: entry.metaDescription,
        publishedAt: new Date(entry.publishedAt),
        status: "PUBLISHED" as const,
        tags: entry.tags,
        title: entry.title,
        type: entry.type,
      };

      await prisma.article.upsert({
        create: {
          ...data,
          authorId: admin.id,
          categories: { connect: categories },
          slug: entry.slug,
        },
        update: {
          ...data,
          categories: { set: categories },
        },
        where: { slug: entry.slug },
      });
    }

    console.info(`${entries.filter((entry) => entry.type === "ARTICLE").length} article(s) and ${entries.filter((entry) => entry.type === "NEWS").length} news item(s) are published.`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
